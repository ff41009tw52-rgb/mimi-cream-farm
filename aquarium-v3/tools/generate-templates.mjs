import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const target = path.join(project, 'aquarium-v3');
const width = 800;
const height = 800 * 210 / 297;
const centers = [[43, 43], [757, 43], [757, height - 43], [43, height - 43]];
const cell = 6;
const colors = [
  ['clown', '小丑魚型', [119, 166, 571, 247]],
  ['butterfly', '蝴蝶魚型', [119, 121, 550, 321]],
  ['puffer', '河豚型', [114, 130, 554, 309]],
  ['shark', '鯊魚型', [114, 170, 593, 231]],
];

function rotate(bits) {
  return bits.map((_, i) => bits[(4 - i % 5) * 5 + Math.floor(i / 5)]);
}
function distance(a, b) {
  return a.reduce((sum, v, i) => sum + Number(v !== b[i]), 0);
}
let rng = 3197281;
const codes = [];
const known = [];
while (codes.length < 16) {
  const bits = Array.from({length:25}, () => {
    rng ^= rng << 13;
    rng ^= rng >>> 17;
    rng ^= rng << 5;
    return rng & 1;
  });
  const white = bits.reduce((a,b) => a+b, 0);
  if (white < 10 || white > 15) continue;
  const rotations = [bits];
  for (let i = 1; i < 4; i++) rotations.push(rotate(rotations[i - 1]));
  if (rotations.some((a,i) => [...known, ...rotations.slice(0,i)].some(b => distance(a,b) < 8))) continue;
  codes.push(bits);
  known.push(...rotations);
}

function marker(center, index) {
  const [x,y] = center.map(v => v - 3.5 * cell);
  const holes = codes[index].flatMap((bit,i) => bit ? [
    `<rect x="${x + (i % 5 + 1) * cell}" y="${y + (Math.floor(i / 5) + 1) * cell}" width="${cell}" height="${cell}"/>`,
  ] : []).join('');
  return `<g><rect x="${x}" y="${y}" width="${7*cell}" height="${7*cell}"/><g fill="#fff">${holes}</g></g>`;
}

const fish = Object.fromEntries(colors.map(([id, name, bounds], index) => {
  const original = readFileSync(path.join(project, 'aquarium-v2/templates', id + '.svg'), 'utf8');
  const outline = original.match(/<path d="([^"]+)"/)[1];
  const details = original.split('/>\n<path d=')[1]?.split(/\n<g /)[0];
  const originalLines = details ? '<path d=' + details : original.match(/\n(<circle .*?)\n<g /)[1];
  const interior = originalLines.replace(/#[a-f0-9]{6}/gi, '#333');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="297mm" height="210mm" viewBox="0 0 ${width} ${height}" role="img" aria-label="${name}著色模板">
<rect width="${width}" height="${height}" fill="white"/>
<g fill="#000">${centers.map((p,i) => marker(p,index*4+i)).join('')}</g>
<g fill="#111" font-family="'Noto Sans CJK TC','Microsoft JhengHei',sans-serif" text-anchor="middle">
<text x="400" y="59" font-size="24" font-weight="700">${name}著色紙</text>
<text x="400" y="88" font-size="15">在魚的輪廓裡自由上色，四個角落的方格請留白。</text>
<text x="400" y="486" font-size="13">A4 橫式・原尺寸列印・保留整張紙</text>
</g>
<path id="fish-outline" d="${outline}" fill="white" stroke="#171717" stroke-width="3.4" stroke-linejoin="round"/>
${interior}
</svg>
`;
  writeFileSync(path.join(target,'templates',id + '.svg'),svg);
  return [id, {name, outline, bounds}];
}));
writeFileSync(path.join(target, 'templates.js'), `// Generated by tools/generate-templates.mjs from the V2 fish paths.\nexport const SHEET = ${JSON.stringify({width,height,centers,cell})};\nexport const FISH = ${JSON.stringify(fish,null,2)};\nexport const CODES = [\n  ${codes.map(bits=>JSON.stringify(bits)).join(',\n  ')}\n];\n`);
