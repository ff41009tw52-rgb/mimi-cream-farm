import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const target = path.join(project, 'aquarium-v3');
const artwork = JSON.parse(readFileSync(path.join(target,'tools/artwork.json'),'utf8'));
const width = 800;
const height = 800 * 210 / 297;
const centers = [[43,43],[757,43],[757,height-43],[43,height-43]];
const cell = 6;
const artworkRevision = 2;
const latestRevisions = {octopus:3};
const originalSpecies = [
  ['clown','小丑魚型',[119,166,571,247]],
  ['butterfly','蝴蝶魚型',[119,121,550,321]],
  ['puffer','河豚型',[114,130,554,309]],
  ['shark','鯊魚型',[114,170,593,231]],
];
const species = [...originalSpecies,
  ['jelly','水母'],
  ['ray','魟魚'],
  ['octopus','章魚'],
  ['turtle','海龜'],
];
// These indices are printed on the worksheets. Keep published groups in order.
const markerGroups = [
  ...originalSpecies.map(([type]) => ({type, revision:1})),
  ...species.map(([type]) => ({type, revision:artworkRevision})),
  {type:'octopus',revision:latestRevisions.octopus},
];

function rotate(bits) {
  return bits.map((_, i) => bits[(4 - i % 5) * 5 + Math.floor(i / 5)]);
}
function distance(a, b) {
  return a.reduce((sum, v, i) => sum + Number(v !== b[i]), 0);
}
let rng = 3197281;
const codes = [];
const known = [];
// The generator appends codes without altering previously published values.
while (codes.length < markerGroups.length * 4) {
  const bits = Array.from({length:25}, () => {
    rng ^= rng << 13;
    rng ^= rng >>> 17;
    rng ^= rng << 5;
    return rng & 1;
  });
  const white = bits.reduce((a,b) => a+b, 0);
  if (white < 10 || white > 15) continue;
  const rotations = [bits];
  for (let i = 1; i < 4; i++) rotations.push(rotate(rotations[i - 1]));
  if (rotations.some((a,i) => [...known, ...rotations.slice(0,i)].some(b => distance(a,b) < 8))) continue;
  codes.push(bits);
  known.push(...rotations);
}

function marker(center, index) {
  const [x,y] = center.map(v => v - 3.5 * cell);
  const holes = codes[index].flatMap((bit,i) => bit ? [
    `<rect x="${x + (i % 5 + 1) * cell}" y="${y + (Math.floor(i / 5) + 1) * cell}" width="${cell}" height="${cell}"/>`,
  ] : []).join('');
  return `<g><rect x="${x}" y="${y}" width="${7*cell}" height="${7*cell}"/><g fill="#fff">${holes}</g></g>`;
}

const legacy = Object.fromEntries(originalSpecies.map(([id, name, bounds]) => {
  const original = readFileSync(path.join(project, 'aquarium-v2/templates', id + '.svg'), 'utf8');
  const outline = original.match(/<path d="([^"]+)"/)[1];
  return [id, {name, outline, bounds, strokeWidth:3.4}];
}));

function shape(name, original) {
  const scale = Math.min(658/original.width,372/original.height);
  const w = original.width*scale, h = original.height*scale;
  const x = (width-w)/2, y = 289-h/2;
  const points=original.outline.map(([u,v])=>[+(x+u*scale).toFixed(2),+(y+v*scale).toFixed(2)]);
  const outline = 'M'+points.map(([u,v])=>`${u} ${v}`).join(' L')+' Z';
  const bounds=[Math.floor(x)-3,Math.floor(y)-3,Math.ceil(w)+7,Math.ceil(h)+7];
  return {name, outline, bounds, strokeWidth:0, x, y, w, h};
}

const oldOctopus=shape('章魚',artwork['octopus-v2']);
const fish = Object.fromEntries(species.map(([id,name]) => {
  const {x,y,w,h,...model}=shape(name,artwork[id]);
  const {outline}=model;
  const bytes = readFileSync(path.join(target,'templates/artwork',id+'.png'));
  const revision=latestRevisions[id] ?? artworkRevision;
  const markerId = markerGroups.findIndex(group=>group.type===id && group.revision===revision)*4;
  const coloringArea = legacy[id] ? '魚的輪廓' : '動物的輪廓';
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="297mm" height="210mm" viewBox="0 0 ${width} ${height}" role="img" aria-label="${name}著色模板">
<rect width="${width}" height="${height}" fill="white"/>
<g fill="#000">${centers.map((p,i) => marker(p,markerId+i)).join('')}</g>
<g fill="#111" font-family="'Noto Sans CJK TC','Microsoft JhengHei',sans-serif" text-anchor="middle">
<text x="400" y="56" font-size="24" font-weight="700">${name}${id==='octopus' ? '（八腕）' : ''}著色紙</text>
<text x="400" y="82" font-size="15">在${coloringArea}裡自由上色，四個角落的方格請留白。</text>
<text x="400" y="513" font-size="13">A4 橫式・原尺寸列印・保留整張紙</text>
</g>
<clipPath id="fish-silhouette"><path d="${outline}"/></clipPath>
<image x="${x}" y="${y}" width="${w}" height="${h}" clip-path="url(#fish-silhouette)" xlink:href="data:image/png;base64,${bytes.toString('base64')}"/>
</svg>
`;
  writeFileSync(path.join(target,'templates',id+'.svg'),svg);
  return [id, model];
}));

writeFileSync(path.join(target,'templates.js'), `// Generated by tools/generate-templates.mjs. Do not edit manually.
export const SHEET = ${JSON.stringify({width,height,centers,cell})};
export const ARTWORK_REVISION = ${artworkRevision};
export const MARKER_GROUPS = ${JSON.stringify(markerGroups)};
export const FISH = ${JSON.stringify(fish,null,2)};
const LEGACY_FISH = ${JSON.stringify(legacy,null,2)};
const OCTOPUS_V2 = ${JSON.stringify({name:oldOctopus.name,outline:oldOctopus.outline,bounds:oldOctopus.bounds,strokeWidth:oldOctopus.strokeWidth})};
export const OCTOPUS_REVISION = ${latestRevisions.octopus};
export function artworkRevisionFor(type) {
  return type==='octopus' ? OCTOPUS_REVISION : ARTWORK_REVISION;
}
export function fishShape(type, revision=artworkRevisionFor(type)) {
  if (revision===1) return LEGACY_FISH[type];
  return type==='octopus' && revision===ARTWORK_REVISION ? OCTOPUS_V2 : FISH[type];
}
export const CODES = [
  ${codes.map(bits=>JSON.stringify(bits)).join(',\n  ')}
];
`);
