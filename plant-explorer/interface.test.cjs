// Student-facing UI regression checks; no network or saved production data.
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const {parseHTML}=require('linkedom');
const source=fs.readFileSync(__dirname+'/../plant-explorer.html','utf8');
const {window}=parseHTML(source),document=window.document;
const main=[...source.matchAll(/<script>([\s\S]*?)<\/script>/g)].map(m=>m[1]).find(s=>s.includes('function buildForm()'));
const ctx=vm.createContext({window,document,crypto:require('node:crypto').webcrypto,console,Intl,Date,URL,Blob,localStorage:{getItem:()=>null,setItem(){}},setTimeout:()=>0,clearTimeout(){},confirm:()=>false});
vm.runInContext(main,ctx);
assert.equal(document.getElementById('sound-btn'),null);
assert(!source.includes('AudioContext'));
assert.equal(document.getElementById('select-plant-preset'),null);
assert.equal(document.getElementById('input-plant-name').value,'');
assert.equal(document.getElementById('input-location').type,'hidden');
assert.equal(document.getElementById('input-location').value,'');
assert(document.getElementById('tab-map').hasAttribute('hidden'));
assert(document.getElementById('section-map').hasAttribute('hidden'));
vm.runInContext("switchTab('map')",ctx);
assert(document.getElementById('section-map').classList.contains('hidden'));
const record={id:'LOCAL-hidden-test-id',name:'測試薄荷',date:'2026-11-05',location:'歷史地點',leafMarginName:'鋸齒狀',leafVenationName:'網狀脈',hasFlower:true,flowerDescription:'白色小花',photoData:'data:image/jpeg;base64,/9j/2Q=='};
ctx.sample=record;vm.runInContext('sharedSpecimens=[sample];renderAlmanac();',ctx);
const card=document.querySelector('.specimen-card');
assert(card.textContent.includes(record.name));assert(card.textContent.includes(record.date));assert(card.textContent.includes(record.location));
assert(!card.textContent.includes('LOCAL-'));assert(!card.textContent.includes('鋸齒狀'));assert.equal(card.querySelectorAll('img').length,0);
card.querySelector('button').onclick();
assert.equal(document.querySelectorAll('#printable-report th').length,2);
assert([...document.querySelectorAll('#print-table-body tr')].every(r=>r.children.length===2));
assert(document.getElementById('print-table-body').textContent.includes('鋸齒狀'));
assert(document.getElementById('print-table-body').textContent.includes('白色小花'));
assert(!document.getElementById('printable-report').textContent.includes('LOCAL-'));
assert(document.getElementById('print-photo-img').src.startsWith('data:image/'));
vm.runInContext('resetForm(true);',ctx);
assert.equal(document.getElementById('input-location').value,'');
assert.equal(vm.runInContext('currentRecord.mapX',ctx),null);
console.log('PASS: no audio/name dropdown/location entry, paused map, compact local cards, hidden IDs, two-column reports with full traits/flowers/photos, blank location for new records.');
